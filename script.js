/* =========================
   이미지 회전
========================= */

let rotation = 0;


function rotateTurnImage(degree) {

  rotation += degree;

  const image =
    document.querySelector(".turn-image");

  if (image) {

    image.style.transform =
      `rotate(${rotation}deg)`;

  }

}



function resetTurnImage() {

  rotation = 0;

  const image =
    document.querySelector(".turn-image");

  if (image) {

    image.style.transform =
      "rotate(0deg)";

  }

}



/* =========================
   화면 이동
========================= */

function goToScreen(screenId) {

  document
    .querySelectorAll(".screen")
    .forEach(screen => {

      screen.classList.remove("active");

    });


  document
    .getElementById(screenId)
    .classList.add("active");

}



/* =========================
   테스트 시작
========================= */

function startTest() {

  currentQuestionIndex = 0;

  userAnswers = [];

  specialQuestions = [];

  currentSpecialQuestionIndex = 0;

  specialAnswers = {};

  finalScores = {};

  resetTurnImage();

  goToScreen("question-screen");

  renderQuestion();

  rotateTurnImage(90);

}



/* =========================
   질문 표시
========================= */

function renderQuestion() {

  const q =
    QUESTIONS[currentQuestionIndex];


  document.getElementById(
    "question-counter"
  ).innerText =
    `질문 ${currentQuestionIndex + 1} / ${QUESTIONS.length}`;


  const percent =
    Math.round(
      ((currentQuestionIndex + 1) /
        QUESTIONS.length) * 100
    );


  document.getElementById(
    "progress-percent"
  ).innerText =
    `${percent}%`;


  document.getElementById(
    "progress-bar"
  ).style.width =
    `${percent}%`;


  document.getElementById(
    "axis-badge"
  ).innerText =
    q.badge;


  document.getElementById(
    "question-text"
  ).innerText =
    q.question;



  /* 양쪽 설명 */

const scaleLeft =
  document.getElementById("scale-left");

const scaleRight =
  document.getElementById("scale-right");


if (scaleLeft) {

  scaleLeft.innerText =
    "그렇다";

}


if (scaleRight) {

  scaleRight.innerText =
    "그렇지 않다";

}



  const prevBtn =
    document.getElementById("prev-btn");


  if (currentQuestionIndex > 0) {

    prevBtn.classList.remove("hidden");

  } else {

    prevBtn.classList.add("hidden");

  }



  document
    .querySelectorAll(".scale-btn")
    .forEach(button => {

      button.classList.remove("selected");

    });



  if (
    userAnswers[currentQuestionIndex] !== undefined
  ) {

    const selectedIndex =
      userAnswers[currentQuestionIndex];

    const buttons =
      document.querySelectorAll(".scale-btn");

    if (buttons[selectedIndex]) {

      buttons[selectedIndex]
        .classList.add("selected");

    }

  }

}



/* =========================
   반대 성향
========================= */

function getOppositeType(type) {

  const opposites = {

    A: "P",
    P: "A",

    M: "D",
    D: "M",

    T: "L",
    L: "T",

    R: "V",
    V: "R"

  };


  return opposites[type];

}



/* =========================
   7단계 척도 선택
========================= */

function selectScale(index) {

  const buttons =
    document.querySelectorAll(".scale-btn");


  buttons.forEach(button => {

    button.classList.remove("selected");

  });


  if (buttons[index]) {

    buttons[index].classList.add("selected");

  }



  userAnswers[currentQuestionIndex] =
    index;



  setTimeout(() => {

    if (
      currentQuestionIndex + 1 <
      QUESTIONS.length
    ) {

      currentQuestionIndex++;

      renderQuestion();

      rotateTurnImage(90);

    } else {

      calculateResult();

    }

  }, 250);

}



/* =========================
   이전 질문
========================= */

function prevQuestion() {

  if (currentQuestionIndex > 0) {

    currentQuestionIndex--;

    renderQuestion();

    rotateTurnImage(-90);

  }

}



/* =========================
   점수 계산
========================= */

function calculateResult() {

  goToScreen("loading-screen");


  setTimeout(() => {

    const scores = {

      A: 0,
      P: 0,

      M: 0,
      D: 0,

      T: 0,
      L: 0,

      R: 0,
      V: 0

    };



    userAnswers.forEach((answerIndex, questionIndex) => {

      const q =
        QUESTIONS[questionIndex];


      if (answerIndex === undefined) {

        return;

      }


      const weights = [

        3,
        2,
        1,
        0,
        -1,
        -2,
        -3

      ];


      const weight =
        weights[answerIndex];


      if (weight > 0) {

        scores[q.direction] += weight;

      } else if (weight < 0) {

        scores[
          getOppositeType(q.direction)
        ] += Math.abs(weight);

      }

    });



    finalScores = scores;


    /* =====================
       동점 축 찾기
    ===================== */

    specialQuestions = [];



    if (scores.A === scores.P) {

      specialQuestions.push({

        axis: "AP",

        badge: "행복의 성격 (A / P)",

        question: "A랑 P가 같을 때의 특수질문",

        option1: "A 유형",

        option2: "P 유형",

        type1: "A",

        type2: "P"

      });

    }



    if (scores.M === scores.D) {

      specialQuestions.push({

        axis: "MD",

        badge: "행복의 지속 (M / D)",

        question: "M이랑 D가 같을 때의 특수질문",

        option1: "M 유형",

        option2: "D 유형",

        type1: "M",

        type2: "D"

      });

    }



    if (scores.T === scores.L) {

      specialQuestions.push({

        axis: "TL",

        badge: "행복의 관계 (T / L)",

        question: "T랑 L이 같을 때의 특수질문",

        option1: "T 유형",

        option2: "L 유형",

        type1: "T",

        type2: "L"

      });

    }



    if (scores.R === scores.V) {

      specialQuestions.push({

        axis: "RV",

        badge: "행복의 환경 (R / V)",

        question: "R이랑 V가 같을 때의 특수질문",

        option1: "R 유형",

        option2: "V 유형",

        type1: "R",

        type2: "V"

      });

    }



    /* =====================
       특수질문 시작
    ===================== */

    if (specialQuestions.length > 0) {

      currentSpecialQuestionIndex = 0;

      setTimeout(() => {

        goToScreen(
          "special-question-screen"
        );

        renderSpecialQuestion();

      }, 300);

      return;

    }



    /* 동점이 없으면 바로 결과 */

    const resultCode =
      getResultCode(scores);


    setTimeout(() => {

      showResultScreen(
        resultCode,
        scores
      );

    }, 300);

  }, 1200);

}



/* =========================
   결과 코드 만들기
========================= */

function getResultCode(scores) {

  const codeAxis1 =
    scores.A > scores.P
      ? "A"
      : "P";


  const codeAxis2 =
    scores.M > scores.D
      ? "M"
      : "D";


  const codeAxis3 =
    scores.T > scores.L
      ? "T"
      : "L";


  const codeAxis4 =
    scores.R > scores.V
      ? "R"
      : "V";


  return `${codeAxis1}${codeAxis2}${codeAxis3}${codeAxis4}`;

}



/* =========================
   특수질문 표시
========================= */

function renderSpecialQuestion() {

  const q =
    specialQuestions[currentSpecialQuestionIndex];


  const total =
    specialQuestions.length;


  const current =
    currentSpecialQuestionIndex + 1;



  /* 질문 번호 */

  document.getElementById(
    "special-question-counter"
  ).innerText =
    `추가 질문 ${current} / ${total}`;



  /* 진행바 */

  const progress =
    (current / total) * 100;


  const progressBar =
    document.getElementById(
      "special-progress-bar"
    );


  if (progressBar) {

    progressBar.style.width =
      `${progress}%`;

  }



  /* 축 이름 */

  document.getElementById(
    "special-axis-badge"
  ).innerText =
    q.badge;



  /* 질문 */

  document.getElementById(
    "special-question-text"
  ).innerText =
    q.question;



  /* 선택지 */

  document.getElementById(
    "special-option-1"
  ).innerText =
    q.option1;


  document.getElementById(
    "special-option-2"
  ).innerText =
    q.option2;

}



/* =========================
   특수질문 답변
========================= */

function selectSpecialAnswer(index) {

  const q =
    specialQuestions[
      currentSpecialQuestionIndex
    ];



  if (index === 0) {

    specialAnswers[q.axis] =
      q.type1;

  } else {

    specialAnswers[q.axis] =
      q.type2;

  }



  /* 다음 특수질문 */

  if (
    currentSpecialQuestionIndex + 1 <
    specialQuestions.length
  ) {

    currentSpecialQuestionIndex++;

    renderSpecialQuestion();

    rotateTurnImage(90);

  } else {

    /* 모든 특수질문 완료 */

    const finalCode =
      buildFinalCode();


    showResultScreen(
      finalCode,
      finalScores
    );

  }

}



/* =========================
   최종 코드 만들기
========================= */

function buildFinalCode() {

  const axis1 =
    specialAnswers.AP ||
    (
      finalScores.A > finalScores.P
        ? "A"
        : "P"
    );


  const axis2 =
    specialAnswers.MD ||
    (
      finalScores.M > finalScores.D
        ? "M"
        : "D"
    );


  const axis3 =
    specialAnswers.TL ||
    (
      finalScores.T > finalScores.L
        ? "T"
        : "L"
    );


  const axis4 =
    specialAnswers.RV ||
    (
      finalScores.R > finalScores.V
        ? "R"
        : "V"
    );


  return `${axis1}${axis2}${axis3}${axis4}`;

}



